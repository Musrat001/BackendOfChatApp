const mongoose = require("mongoose");
const MessageSchema = mongoose.Schema({
    senderId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true
    },
    receiverId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true
    },
    text: {
        type: String
    },
    image: {
        type: String
    }
})

const MessageModel = new mongoose.model("Message", MessageSchema);
module.exports = {
    MessageModel
}